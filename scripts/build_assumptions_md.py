def fmt_value(item: dict) -> str:
    v, unit = item["value"], item.get("unit", "")
    if unit == "PHP thousands":
        return f"₱{v / 1_000:,.1f}m"
    if unit == "decimal":
        return f"{v:.3%}"
    if unit == "PHP per share":
        return f"₱{v:,.2f}"
    if unit == "shares":
        return f"{v:,.0f}"
    return f"{v:g}{'x' if unit == 'x' else ''}"


def fmt_dist(spec: dict) -> str:
    if "triangular" in spec:
        t = spec["triangular"]
        return f"Triangular: low {t['low']:.2%}, most likely {t['mode']:.2%}, high {t['high']:.2%}"
    if "truncated_normal" in spec:
        t = spec["truncated_normal"]
        return f"Truncated normal: mean {t['mean']:g}, s.d. {t['sd']:g}, bounds {t['low']:g} to {t['high']:g}"
    if "fixed" in spec:
        return f"Fixed: {spec['fixed']['value']:.2%}"
    if "value" in spec:
        return f"{spec['value']:g}"
    return ""


def short_source(src: str) -> str:
    return src.split(". http")[0]


def build() -> str:
    co = load_yaml(DEFAULT_COMPANY)
    a = load_yaml(DEFAULT_ASSUMPTIONS)
    lines = [
        "# Assumptions and sources: Monde Nissin valuation",
        "",
        "Generated by `scripts/build_assumptions_md.py` from `config/monde.yaml` and `config/monde_assumptions.yaml`. Do not edit by hand.",
        "",
        "There are two kinds of input. **Facts** are copied from a cited public source. **Assumptions** are judgements about the future; each has a range and a reason.",
        "",
        "## 1. Assumptions (judgements)",
        "",
        "| Driver | Distribution | Why |",
        "|---|---|---|",
    ]
    d = a["drivers"]
    for year, spec in d["revenue_growth"].items():
        lines.append(f"| Revenue growth {year} | {fmt_dist(spec)} | {spec['why']} |")
    for key, label in (
        ("ebitda_margin", "EBITDA margin"),
        ("da_pct_revenue", "D&A % of revenue"),
        ("capex_pct_revenue", "Capex % of revenue"),
        ("nwc_pct_revenue_change", "NWC % of revenue change"),
        ("tax_rate", "Tax rate"),
        ("terminal_growth", "Terminal growth g"),
    ):
        lines.append(f"| {label} | {fmt_dist(d[key])} | {d[key]['why']} |")
    w = a["wacc"]
    for key, label in (
        ("risk_free", "Risk-free rate"),
        ("beta", "Beta"),
        ("equity_risk_premium", "Equity risk premium"),
    ):
        lines.append(f"| {label} | {fmt_dist(w[key])} | {w[key]['why']} |")
    lines.append(
        f"| Pre-tax cost of debt | 10-year yield + {w['pre_tax_cost_of_debt']['spread_over_government']:.2%} | {w['pre_tax_cost_of_debt']['why']} |"
    )
    lines.append(f"| Capital weights | Market values | {w['weights']['why']} |")
    sim = a["simulation"]
    lines.append(
        f"| Growth autocorrelation | {sim['growth_autocorrelation']['value']} | {sim['growth_autocorrelation']['why']} |"
    )
    lines.append(
        f"| Growth-margin correlation | {sim['growth_margin_correlation']['value']} | {sim['growth_margin_correlation']['why']} |"
    )
    lines += [
        "",
        f"Simulation: {sim['n_sims']:,} runs, seed {sim['seed']}, {sim['method']} sampling.",
        "",
        "## 2. Judgement calls in the equity bridge and set-up",
        "",
        "| Item | Treatment |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in JUDGEMENT_CALLS]
    lines += [
        "",
        "## 3. Facts and their sources",
        "",
        "| Item | Value | As of | Where | Source |",
        "|---|---|---|---|---|",
    ]
    for path, item in iter_sourced({k: v for k, v in co.items() if k not in ("company", "sources")}):
        lines.append(
            f"| `{path}` | {fmt_value(item)} | {item.get('as_of', '')} | {item.get('where', '')} | {short_source(item['source'])} |"
        )
    lines += ["", "## 4. Full source list", ""]
    lines += [f"- {src}" for src in co["sources"].values()]
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
